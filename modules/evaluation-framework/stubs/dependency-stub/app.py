"""Dependency-stub service for Evaluation Framework.

Stands in for LLM Gateway — the LLD's Deployability and Testability
Contract: "Runs and tests fully with LLM Gateway stubbed." `/v1/complete`
backs the real `deepeval.metrics.FaithfulnessMetric` pipeline
(core/deepeval_adapter.py): DeepEval's own prompt templates ask this
stub, in turn, for truths/claims extraction and per-claim verdicts, so
this scripted responder mirrors the one in core/fakes.py — self-contained
here (this stub ships with no import on the main package, matching every
other module's dependency-stub) rather than shared code.
"""
from __future__ import annotations

import ast
import json
import re
from collections import Counter

from fastapi import FastAPI
from pydantic import BaseModel

app = FastAPI(title="Evaluation Framework dependency stub")

_TOKEN_RE = re.compile(r"[a-z0-9]+")


def _tokenize(text: str) -> Counter:
    return Counter(_TOKEN_RE.findall(text.lower()))


def _claim_recall(claim_tokens: Counter, context_tokens: Counter) -> float:
    total = sum(claim_tokens.values())
    if total == 0:
        return 1.0
    supported = sum(min(count, context_tokens.get(token, 0)) for token, count in claim_tokens.items())
    return supported / total


def _extract_between(text: str, start_marker: str, end_marker: str) -> str:
    start = text.find(start_marker)
    if start == -1:
        return ""
    start += len(start_marker)
    end = text.find(end_marker, start)
    return text[start:].strip() if end == -1 else text[start:end].strip()


class JudgeRequest(BaseModel):
    agent_output: str
    metric_name: str
    reference_data: dict


class CompleteRequest(BaseModel):
    prompt: str


@app.post("/v1/judge")
async def judge(body: JudgeRequest) -> dict:
    return {"score": 0.8}


@app.post("/v1/complete")
async def complete(body: CompleteRequest) -> dict:
    prompt = body.prompt

    if "please generate a comprehensive list of FACTUAL" in prompt:
        text = _extract_between(prompt, "Text:\n", "\n\nJSON:")
        return {"text": json.dumps({"truths": [text] if text else []})}

    if "please extract a comprehensive list of FACTUAL" in prompt:
        text = _extract_between(prompt, "AI Output:\n", "\n\nJSON:")
        return {"text": json.dumps({"claims": [text] if text else []})}

    if "generate a list of JSON objects to indicate whether EACH claim contradicts" in prompt:
        match = re.search(r"Retrieval Contexts:\n(.*?)\n\nClaims:\n(\[.*?\])\n\nJSON:", prompt, re.DOTALL)
        if not match:
            return {"text": json.dumps({"verdicts": []})}
        context_tokens = _tokenize(match.group(1))
        claims = ast.literal_eval(match.group(2))
        verdicts = [
            {"verdict": "yes"} if _claim_recall(_tokenize(claim), context_tokens) >= 0.5
            else {"verdict": "no", "reason": "not supported by the retrieval context"}
            for claim in claims
        ]
        return {"text": json.dumps({"verdicts": verdicts})}

    if "Given the faithfulness score, which is a 0-1 score" in prompt:
        return {"text": json.dumps({"reason": "Generated by the dependency stub for offline testing."})}

    return {"text": "{}"}


@app.get("/healthz")
async def healthz() -> dict:
    return {"status": "ok"}

@app.get("/v1/multi-tenancy/tenants/{tenant_id}/gate")
async def gate(tenant_id: str, module: str | None = None) -> dict:
    return {"allowed": True, "reason": "active"}
